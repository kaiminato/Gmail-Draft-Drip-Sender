import {
  boolean,
  index,
  integer,
  pgTable,
  text,
  timestamp,
  uuid,
} from "drizzle-orm/pg-core";

export const managers = pgTable("managers", {
  id: uuid("id").primaryKey().defaultRandom(),
  name: text("name").notNull(),
  createdAt: timestamp("created_at", { withTimezone: true }).notNull().defaultNow(),
});

// One row per extension install. `deviceId` is the install's own UUID and the
// real identity; `email` is filled in once the extension manages to read it
// off the Gmail page.
export const accounts = pgTable(
  "accounts",
  {
    id: uuid("id").primaryKey().defaultRandom(),
    deviceId: text("device_id").notNull().unique(),
    email: text("email"),
    managerId: uuid("manager_id").references(() => managers.id, { onDelete: "set null" }),
    version: text("version"),

    // Last reported by the extension.
    running: boolean("running").notNull().default(false),
    busy: boolean("busy").notNull().default(false),
    stopReason: text("stop_reason"),
    gmailTabOpen: boolean("gmail_tab_open").notNull().default(false),
    tier: text("tier").notNull().default("normal"), // few | less | normal | many
    tierSetAt: timestamp("tier_set_at", { withTimezone: true }),
    dayTarget: integer("day_target"),
    plannedLeft: integer("planned_left"),
    restStart: text("rest_start"),
    restEnd: text("rest_end"),
    nextSendAt: timestamp("next_send_at", { withTimezone: true }),
    lastSendAt: timestamp("last_send_at", { withTimezone: true }),
    remainingBucket: text("remaining_bucket").notNull().default("unknown"),
    remainingCount: integer("remaining_count"),
    sentToday: integer("sent_today").notNull().default(0),
    sentDate: text("sent_date"),
    totalSent: integer("total_sent").notNull().default(0),
    bounceCount: integer("bounce_count").notNull().default(0),
    blockCount: integer("block_count").notNull().default(0),
    consecutiveFailures: integer("consecutive_failures").notNull().default(0),

    // A queued start/stop, cleared when the extension acks it. A start carries
    // the tier to run on.
    pendingCommand: text("pending_command"),
    pendingCommandId: text("pending_command_id"),
    pendingTier: text("pending_tier"),
    pendingCommandAt: timestamp("pending_command_at", { withTimezone: true }),

    lastSeenAt: timestamp("last_seen_at", { withTimezone: true }),
    createdAt: timestamp("created_at", { withTimezone: true }).notNull().defaultNow(),
  },
  (t) => [index("accounts_manager_idx").on(t.managerId)],
);

// Everything the statistics are built from. `id` is generated by the
// extension so a re-sent batch is a no-op.
export const events = pgTable(
  "events",
  {
    id: text("id").primaryKey(),
    accountId: uuid("account_id")
      .notNull()
      .references(() => accounts.id, { onDelete: "cascade" }),
    type: text("type").notNull(), // sent | failed | blocked | bounce | started | stopped
    reason: text("reason"),
    subject: text("subject"),
    recipient: text("recipient"),
    message: text("message"),
    occurredAt: timestamp("occurred_at", { withTimezone: true }).notNull(),
    receivedAt: timestamp("received_at", { withTimezone: true }).notNull().defaultNow(),
  },
  (t) => [
    index("events_account_time_idx").on(t.accountId, t.occurredAt),
    index("events_type_time_idx").on(t.type, t.occurredAt),
  ],
);

// Key/value for the few dashboard-wide settings (the admin password hash).
export const settings = pgTable("settings", {
  key: text("key").primaryKey(),
  value: text("value").notNull(),
  updatedAt: timestamp("updated_at", { withTimezone: true }).notNull().defaultNow(),
});

// Extra Google accounts allowed to sign in, on top of the built-in list.
export const adminEmails = pgTable("admin_emails", {
  email: text("email").primaryKey(),
  addedBy: text("added_by"),
  createdAt: timestamp("created_at", { withTimezone: true }).notNull().defaultNow(),
});

export type Manager = typeof managers.$inferSelect;
export type Account = typeof accounts.$inferSelect;
export type Event = typeof events.$inferSelect;
